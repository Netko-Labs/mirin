/**
 * Generate `src/themes.generated.ts` from shadcn's registry themes (oklch CSS
 * variables) as `#RRGGBB[AA]` tokens the Metal renderer accepts.
 * Usage: bun scripts/gen-themes.ts <path-to-shadcn>/apps/v4/registry/themes.ts
 */

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { oklchToHex } from "./lib/color.ts";

const source = Bun.argv[2];
if (!source) throw new Error("usage: bun scripts/gen-themes.ts <themes.ts>");
const text = await Bun.file(source).text();

const camel = (name: string) => name.replace(/-([a-z0-9])/g, (_, ch: string) => ch.toUpperCase());
const themes: Record<
  string,
  { light: Record<string, string>; dark: Record<string, string>; radius: number }
> = {};
const blocks = text.split(/\n {2}\{\n {4}name: "/).slice(1);
for (const block of blocks) {
  const name = block.slice(0, block.indexOf('"'));
  const pick = (mode: "light" | "dark") => {
    const start = block.indexOf(`${mode}: {`);
    if (start < 0) return {};
    const end = block.indexOf("}", start);
    const out: Record<string, string> = {};
    for (const line of block.slice(start, end).split("\n")) {
      const kv = line.match(/^\s*"?([\w-]+)"?:\s*"([^"]+)"/);
      if (!kv) continue;
      const [, key = "", raw = ""] = kv;
      if (key === "radius") continue;
      const hex = oklchToHex(raw);
      if (hex) out[camel(key)] = hex;
    }
    return out;
  };
  const radius = block.match(/radius:\s*"([\d.]+)rem"/);
  const light = pick("light");
  const dark = pick("dark");
  if (Object.keys(light).length > 10) {
    themes[name] = { light, dark, radius: radius ? Number(radius[1]) * 16 : 10 };
  }
}
const out = `/**
 * shadcn/ui registry themes (oklch CSS variables converted to hex).
 * Generated by scripts/gen-themes.ts; do not edit by hand.
 */

export const THEMES = ${JSON.stringify(themes, null, 2)} as const;
`;
writeFileSync(join(import.meta.dir, "..", "src", "themes.generated.ts"), out);
console.log(`wrote ${Object.keys(themes).length} themes: ${Object.keys(themes).join(", ")}`);
