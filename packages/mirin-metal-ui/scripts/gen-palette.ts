/**
 * Generate `src/tw/palette.generated.ts`: Tailwind v4's default color palette
 * (`--color-<name>-<shade>` in tailwindcss/theme.css, oklch) as sRGB hex.
 *
 *   bun scripts/gen-palette.ts <path/to/tailwindcss/theme.css>
 */

import { oklchToHex } from "./lib/color.ts";

const source = Bun.argv[2];
if (!source) throw new Error("usage: bun scripts/gen-palette.ts <tailwindcss/theme.css>");
const css = await Bun.file(source).text();
const entries: string[] = [];
for (const match of css.matchAll(/^\s*--color-([a-z]+-\d+):\s*(oklch\([^)]*\));/gm)) {
  const hex = oklchToHex(match[2] ?? "");
  if (!hex) throw new Error(`cannot convert ${match[1]}: ${match[2]}`);
  entries.push(`  "${match[1]}": "${hex}",`);
}
const out = new URL("../src/tw/palette.generated.ts", import.meta.url).pathname;
await Bun.write(
  out,
  `// Generated by scripts/gen-palette.ts from Tailwind v4's theme.css. Do not edit.\n\n/** Tailwind v4 default palette, \`<color>-<shade>\` → sRGB hex. */\nexport const TAILWIND_PALETTE: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`${entries.length} colors → ${out}`);
