/**
 * Generate `src/icons/generated.ts`: every lucide icon under its lucide-react
 * names (`ChevronRight`, `ChevronRightIcon`, `LucideChevronRight`).
 * Usage: bun scripts/gen-icons.ts
 */

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import * as lucide from "lucide";

const names = Object.keys(lucide)
  .filter((name) => Array.isArray((lucide as Record<string, unknown>)[name]))
  .sort();
const lines = names.map(
  (name) =>
    `export const ${name} = createLucideIcon("${name}", lucide.${name});\nexport { ${name} as ${name}Icon, ${name} as Lucide${name} };`,
);
const out = `/**
 * Every lucide icon under its lucide-react names. Generated by
 * scripts/gen-icons.ts from the \`lucide\` package; do not edit by hand.
 */

import * as lucide from "lucide";
import { createLucideIcon } from "./create.tsx";

${lines.join("\n")}
`;
writeFileSync(join(import.meta.dir, "..", "src", "icons", "icons.generated.ts"), out);
console.log(`wrote ${names.length} icons`);
