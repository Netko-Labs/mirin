/**
 * Generate the lucide icons under their lucide-react names (`ChevronRight`,
 * `ChevronRightIcon`, `LucideChevronRight`). Each icon names the file of the
 * `lucide` package that holds its vector data and reads it when it first
 * renders: importing the icons loads none of the data (the whole of `lucide`
 * is 2,000 modules, 16 ms and 8 MB of every start).
 *
 * Two files: `src/icons/core.generated.ts` holds the icons metal-ui's own
 * components draw (`CORE` below) with their data, which they import from
 * there, and `src/icons/icons.generated.ts` the rest. A module with thousands of exports
 * costs a start about 10 ms and 5 MB however little each export does, so an
 * app that uses the components and imports no icon of its own doesn't load it.
 * Usage: bun scripts/gen-icons.ts
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import * as lucide from "lucide";

/** What `src/components` draws: add a name here before importing it from `core.generated.ts`. */
const CORE = new Set([
  "ArrowDown",
  "ArrowLeft",
  "ArrowRight",
  "Check",
  "ChevronDown",
  "ChevronLeft",
  "ChevronRight",
  "ChevronUp",
  "Circle",
  "CircleCheck",
  "GripVertical",
  "Info",
  "Loader2",
  "Minus",
  "MoreHorizontal",
  "OctagonX",
  "PanelLeft",
  "Search",
  "TriangleAlert",
  "X",
]);

const names = Object.keys(lucide)
  .filter((name) => Array.isArray((lucide as Record<string, unknown>)[name]))
  .sort();

// lucide's ESM entry re-exports each icon (and its aliases) from its own file.
const esm = join(dirname(Bun.resolveSync("lucide/package.json", import.meta.dir)), "dist", "esm");
const fileOf = new Map<string, string>();
const exports = readFileSync(join(esm, "iconsAndAliases.mjs"), "utf8");
for (const match of exports.matchAll(/export \{ ([^}]+) \} from '\.\/icons\/([^']+)\.mjs';/g)) {
  const [, list = "", file = ""] = match;
  for (const part of list.split(",")) fileOf.set(part.trim().replace(/^default as /, ""), file);
}

const core: string[] = [];
const rest: string[] = [];
for (const name of names) {
  const file = fileOf.get(name);
  if (!file || !existsSync(join(esm, "icons", `${file}.mjs`))) {
    throw new Error(`no lucide file for ${name}`);
  }
  // The file must hold what the package's entry exports under this name.
  const loaded = (await import(join(esm, "icons", `${file}.mjs`))) as { default: unknown };
  if (
    JSON.stringify(loaded.default) !== JSON.stringify((lucide as Record<string, unknown>)[name])
  ) {
    throw new Error(`lucide/dist/esm/icons/${file}.mjs is not ${name}`);
  }
  const names = `export { ${name} as ${name}Icon, ${name} as Lucide${name} };`;
  if (CORE.has(name)) {
    // The components' own icons carry their data: a first `require()` costs a
    // process 2 to 4 ms, and an app that draws only these never makes one.
    core.push(
      `export const ${name} = /* @__PURE__ */ icon("${name}", ${JSON.stringify(loaded.default)});\n${names}`,
    );
  } else {
    rest.push(
      `export const ${name} = /* @__PURE__ */ icon("${name}", () => require("lucide/dist/esm/icons/${file}.mjs"));\n${names}`,
    );
  }
}
if (core.length !== CORE.size) throw new Error("a CORE name is not a lucide icon");

const header = (what: string, data: string) => `/**
 * ${what} Generated by
 * scripts/gen-icons.ts from the \`lucide\` package; do not edit by hand.
 * ${data}
 */

import { createLucideIcon as icon } from "./create.tsx";
`;
const dir = join(import.meta.dir, "..", "src", "icons");
writeFileSync(
  join(dir, "core.generated.ts"),
  `${header("The lucide icons metal-ui's own components draw, under their lucide-react names.", "Each carries its vector data.")}\n${core.join("\n")}\n`,
);
writeFileSync(
  join(dir, "icons.generated.ts"),
  `${header("Every other lucide icon under its lucide-react names (the components' own are in core.generated.ts).", "An icon reads its vector data (one file of `lucide`) when it first renders.")}\n${rest.join("\n")}\n`,
);
console.log(`wrote ${names.length} icons (${core.length} in core)`);
